let currentLanguage = localStorage.getItem("portfolio-language") || "pt";

function applyLanguage(language) {
  currentLanguage = language;
  localStorage.setItem("portfolio-language", language);
  document.documentElement.lang = language === "pt" ? "pt-BR" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.getAttribute("data-i18n");
    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.getAttribute("data-i18n-placeholder");
    if (translations[language][key]) {
      element.placeholder = translations[language][key];
    }
  });

  document.querySelectorAll(".language-option").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === language);
  });
}

function initLanguageToggle() {
  document.querySelectorAll(".language-option").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });
  applyLanguage(currentLanguage);
}

function renderTechIcons(container, techIcons) {
  container.innerHTML = "";
  techIcons.forEach((tech) => {
    const item = document.createElement("span");
    item.className = "tech-logo-item";
    item.title = tech.label;

    const icon = document.createElement("img");
    icon.src = tech.src;
    icon.alt = tech.label;

    const label = document.createElement("span");
    label.textContent = tech.label;

    item.append(icon, label);
    container.appendChild(item);
  });
}

function initModal() {
  const modal = document.getElementById("projectModal");
  const closeModalBtn = document.getElementById("closeModal");
  if (!modal || !closeModalBtn) return;

  function openModal(projectKey) {
    const project = projectContent[currentLanguage][projectKey];
    if (!project) return;

    document.getElementById("modalImage").src = project.image;
    document.getElementById("modalImage").alt = project.title;
    document.getElementById("modalTitle").textContent = project.title;
    document.getElementById("modalDescription").textContent = project.description;
    document.getElementById("modalDate").textContent = `${translations[currentLanguage].yearLabel} ${project.date}`;
    document.getElementById("modalProjectLink").href = project.projectLink;
    document.getElementById("modalRepoLink").href = project.repoLink;
    renderTechIcons(document.getElementById("modalTechLogos"), project.techIcons);

    const list = document.getElementById("modalFeatures");
    list.innerHTML = "";
    project.features.forEach((feature) => {
      const item = document.createElement("li");
      item.textContent = feature;
      list.appendChild(item);
    });

    modal.classList.add("active");
    modal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  }

  function closeModal() {
    modal.classList.remove("active");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
  }

  document.querySelectorAll(".project-card").forEach((card) => {
    card.addEventListener("click", () => openModal(card.getAttribute("data-project")));
  });

  closeModalBtn.addEventListener("click", closeModal);
  modal.addEventListener("click", (event) => {
    if (event.target === modal) closeModal();
  });
  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeModal();
  });
}

function initProjectFilter() {
  const buttons = document.querySelectorAll(".filter-btn");
  const cards = document.querySelectorAll(".project-card");
  buttons.forEach((button) => {
    button.addEventListener("click", () => {
      document.querySelector(".filter-btn.active")?.classList.remove("active");
      button.classList.add("active");
      const filter = button.getAttribute("data-filter");
      cards.forEach((card) => {
        const match = filter === "all" || card.getAttribute("data-category") === filter;
        card.classList.toggle("hidden", !match);
      });
    });
  });
}

function initCarousel() {
  const track = document.getElementById("skillsTrack");
  if (!track) return;
  const original = track.innerHTML;
  track.innerHTML += original + original;

  let position = 0;
  let paused = false;
  const speed = 0.45;

  track.addEventListener("mouseenter", () => {
    paused = true;
  });
  track.addEventListener("mouseleave", () => {
    paused = false;
  });

  function animate() {
    if (!paused) {
      position -= speed;
      if (Math.abs(position) >= track.scrollWidth / 3) position = 0;
      track.style.transform = `translateX(${position}px)`;
    }
    requestAnimationFrame(animate);
  }
  animate();
}

document.addEventListener("DOMContentLoaded", () => {
  initLanguageToggle();
  initModal();
  initProjectFilter();
  initCarousel();
});
